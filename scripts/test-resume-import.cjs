const {app,BrowserWindow,ipcMain}=require('electron');
const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
app.setPath('userData',path.join(root,'work','resume-import-test'));
let saves=0, fail=true;
const data={profile:{name:'已有姓名',projects:'已有项目'},applications:[]};
ipcMain.on('data:initial',e=>{e.returnValue={status:'loaded',source:'main',file:'演示',data};});
ipcMain.handle('update:check',()=>({available:false}));
ipcMain.handle('resume:pick',()=>({name:'演示.pdf',path:'演示.pdf',updatedAt:new Date().toISOString()}));
ipcMain.handle('resume:extract',()=>({text:'姓名：测试用户\n邮箱 demo@example.com\n教育经历：演示大学\n本科\n项目经历：新项目',pages:[{number:1,method:'text'}],totalPages:1,processedPages:1,warnings:[]}));
ipcMain.handle('data:save',(_,patch)=>{if(patch.profile){saves++;if(fail)throw new Error('simulated failure');}Object.assign(data,patch);return data;});
app.whenReady().then(async()=>{
  const win=new BrowserWindow({width:1280,height:820,show:false,webPreferences:{preload:path.join(root,'electron','preload.cjs'),sandbox:true,backgroundThrottling:false,offscreen:true}});
  const wait=()=>new Promise(r=>setTimeout(r,150));
  const click=async label=>{await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()===${JSON.stringify(label)}).click()`);await wait();};
  await win.loadFile(path.join(root,'dist','index.html'));await wait();await click('简历');await click('选择简历');
  assert.equal(saves,0);
  await new Promise(r=>setTimeout(r,700));
  assert.ok(await win.webContents.executeJavaScript("Boolean(document.querySelector('[role=dialog]'))"));
  await fs.mkdir(path.join(root,'work'),{recursive:true});
  await fs.writeFile(path.join(root,'work','resume-import-preview.png'),(await win.webContents.capturePage()).toPNG());
  await click('取消');assert.equal(saves,0);
  await click('重新提取资料');await click('确认导入');
  assert.equal(saves,1);assert.ok(await win.webContents.executeJavaScript("document.querySelector('[role=alert]').textContent.includes('保存失败')"));
  fail=false;await click('确认导入');assert.equal(saves,2);assert.equal(data.profile.name,'已有姓名');assert.equal(data.profile.projects,'已有项目');assert.equal(data.profile.email,'demo@example.com');assert.equal(data.profile.education,'演示大学\n本科');
  assert.equal(await win.webContents.executeJavaScript("Boolean(document.querySelector('[role=dialog]'))"),false);
  win.destroy(); console.log('PASS: cancel, selection, failed save, retry and committed state');app.quit();
}).catch(error=>{console.error(error);app.exit(1);});
